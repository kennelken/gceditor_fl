fn parse_vec<T, F: Fn(&serde_json::Value) -> T>(val: Option<&serde_json::Value>, parse_elem: F) -> Vec<T> {
    val.and_then(|v| v.as_array())
        .map(|arr| arr.iter().map(&parse_elem).collect())
        .unwrap_or_default()
}

fn parse_hash_map<T, F: Fn(&serde_json::Value) -> T>(val: Option<&serde_json::Value>, parse_elem: F) -> HashMap<String, T> {
    val.and_then(|v| v.as_object())
        .map(|obj| obj.iter().map(|(k, v)| (k.clone(), parse_elem(v))).collect())
        .unwrap_or_default()
}
