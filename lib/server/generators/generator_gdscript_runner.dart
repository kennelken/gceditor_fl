  static String _escapeIdentifier(String id) {
    if (_gdscriptReservedAndNative.contains(id)) {
      return '${id}_';
    }
    return id;
  }

  String _getEnums(DbModel model, GeneratorGdscript data) {
    final sb = StringBuffer();
    for (final enumEntity in model.cache.allEnums) {
      if (enumEntity.description.isNotEmpty) {
        sb.writeln('## ${enumEntity.description}');
      }
      final enumName = '${data.prefix}${enumEntity.id}${data.postfix}';
      sb.writeln('enum $enumName {');
      for (var i = 0; i < enumEntity.values.length; i++) {
        final val = enumEntity.values[i];
        final escapedId = _escapeIdentifier(val.id);
        sb.writeln('${_indent}$escapedId = $i,');
      }
      sb.writeln('}');
      sb.writeln();
    }
    return sb.toString();
  }

  String _getClasses(DbModel model, GeneratorGdscript data) {
    final items = <String>[];
    // Sort base classes before derived classes
    final allClassesSorted = model.cache.allClasses.orderBy((e) => model.cache.getParentClasses(e).length).toList();

    for (final classEntity in allClassesSorted) {
      if (classEntity.classType == ClassType.undefined || classEntity.classType == ClassType.interface) {
        continue;
      }

      final isValueType = classEntity.classType == ClassType.valueType;
      final parentClass = classEntity.parent != null && classEntity.parent!.isNotEmpty
          ? '${data.prefix}${classEntity.parent}${data.postfix}'
          : 'Base${data.prefix}Item${data.postfix}';

      final properties = <String>[];
      final cloneProperties = <String>[];

      for (final field in classEntity.fields) {
        final propType = _getPropertyType(field, data, model);
        final defaultVal = _getDefaultPropertyValue(field, data, model);
        final escapedId = _escapeIdentifier(field.id);
        properties.add('${_indent}var $escapedId: $propType = $defaultVal');
      }

      for (final field in model.cache.getAllFields(classEntity)) {
        final escapedId = _escapeIdentifier(field.id);
        if (field.typeInfo.type == ClassFieldType.list ||
            field.typeInfo.type == ClassFieldType.set ||
            field.typeInfo.type == ClassFieldType.listInline) {
          cloneProperties.add('${_indent}${_indent}result.$escapedId = $escapedId.duplicate(true)');
        } else if (field.typeInfo.type == ClassFieldType.dictionary) {
          cloneProperties.add('${_indent}${_indent}result.$escapedId = $escapedId.duplicate(true)');
        } else {
          cloneProperties.add('${_indent}${_indent}result.$escapedId = $escapedId');
        }
      }

      final typeNames = _getParentTypeNames(model, data, classEntity);
      final typeNamesLiteral = typeNames.map((e) => '"$e"').join(', ');

      final className = '${data.prefix}${classEntity.id}${data.postfix}';
      final sb = StringBuffer();
      if (classEntity.description.isNotEmpty) {
        sb.writeln('## ${classEntity.description}');
      }
      sb.writeln('class $className extends $parentClass:');
      if (isValueType) {
        sb.writeln('${_indent}func is_value_type() -> bool:');
        sb.writeln('${_indent}${_indent}return true');
      }
      if (properties.isEmpty) {
        sb.writeln('${_indent}pass');
      } else {
        for (final p in properties) {
          sb.writeln(p);
        }
      }
      sb.writeln();
      sb.writeln('${_indent}func get_type_names() -> Array:');
      sb.writeln('${_indent}${_indent}return [$typeNamesLiteral]');
      sb.writeln();
      sb.writeln('${_indent}func clone() -> $className:');
      sb.writeln('${_indent}${_indent}var result = $className.new()');
      sb.writeln('${_indent}${_indent}result.id = id');
      sb.writeln('${_indent}${_indent}result.is_global = is_global');
      for (final cp in cloneProperties) {
        sb.writeln(cp);
      }
      sb.writeln('${_indent}${_indent}return result');
      sb.writeln();
      sb.writeln('${_indent}func _to_string() -> String:');
      sb.writeln('${_indent}${_indent}return "$className {id: %s}" % id');
      sb.writeln();

      items.add(sb.toString());
    }

    return items.join(_defaultNewLine);
  }

  Set<String> _getParentTypeNames(DbModel model, GeneratorGdscript data, ClassMetaEntity classEntity) {
    final typeNames = <String>{};

    // 1. Current class
    typeNames.add(classEntity.id);
    typeNames.add('${data.prefix}${classEntity.id}${data.postfix}');

    // 2. Parent classes (if reference type)
    if (classEntity.classType != ClassType.valueType) {
      final parentClasses = model.cache.getParentClasses(classEntity);
      for (final parent in parentClasses) {
        typeNames.add(parent.id);
        typeNames.add('${data.prefix}${parent.id}${data.postfix}');
      }
    }

    // 3. All interfaces (direct and inherited from parent classes and parent interfaces)
    final allInterfaces = _getAllInterfaces(model, classEntity);
    for (final iface in allInterfaces) {
      typeNames.add(iface.id);
      typeNames.add('${data.prefix}${iface.id}${data.postfix}');
    }

    return typeNames;
  }

  Set<ClassMetaEntity> _getAllInterfaces(DbModel model, ClassMetaEntity classEntity) {
    final result = <ClassMetaEntity>{};

    void collectFrom(ClassMetaEntity entity) {
      final ifaces = model.cache.getParentInterfaces(entity);
      for (final iface in ifaces) {
        result.add(iface);
      }
    }

    collectFrom(classEntity);

    if (classEntity.classType != ClassType.valueType) {
      final parentClasses = model.cache.getParentClasses(classEntity);
      for (final parent in parentClasses) {
        collectFrom(parent);
      }
    }

    return result;
  }

  String _getPropertyType(ClassMetaFieldDescription field, GeneratorGdscript data, [DbModel? model]) {
    switch (field.typeInfo.type) {
      case ClassFieldType.bool:
        return 'bool';
      case ClassFieldType.int:
      case ClassFieldType.long:
      case ClassFieldType.date:
      case ClassFieldType.duration:
        return 'int';
      case ClassFieldType.float:
      case ClassFieldType.double:
        return 'float';
      case ClassFieldType.string:
      case ClassFieldType.text:
      case ClassFieldType.undefined:
        return 'String';
      case ClassFieldType.color:
        return 'Color';
      case ClassFieldType.vector2:
        return 'Vector2';
      case ClassFieldType.vector2Int:
        return 'Vector2i';
      case ClassFieldType.vector3:
        return 'Vector3';
      case ClassFieldType.vector3Int:
        return 'Vector3i';
      case ClassFieldType.vector4:
        return 'Vector4';
      case ClassFieldType.vector4Int:
        return 'Vector4i';
      case ClassFieldType.rectangle:
        return 'Rect2';
      case ClassFieldType.rectangleInt:
        return 'Rect2i';
      case ClassFieldType.reference:
        if (model != null && field.typeInfo.classId != null) {
