      case ClassFieldType.dictionary:
        final keyParser = _getSimpleValueLambda(model, data, field.keyTypeInfo!);
        final valParser = _getSimpleValueLambda(model, data, field.valueTypeInfo!);
        return '_parse_dictionary($rawVal, $keyParser, $valParser, context)';
    }
  }

