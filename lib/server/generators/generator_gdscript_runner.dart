  String _getAssignValuesCases(DbModel model, GeneratorGdscript data) {
    final sb = StringBuffer();
    for (final classEntity in model.cache.allClasses) {
      if (classEntity.classType == ClassType.undefined || classEntity.classType == ClassType.interface) {
        continue;
      }
      final className = '${data.prefix}${classEntity.id}${data.postfix}';
      sb.writeln('${_indent}if instance is $className:');
      final allFields = model.cache.getAllFields(classEntity);
      if (allFields.isEmpty) {
        sb.writeln('${_indent}${_indent}pass');
      } else {
        for (final field in allFields) {
          final parseExpr = _getAssignValueFunction(model, data, field);
          final escapedId = _escapeIdentifier(field.id);
          sb.writeln('${_indent}${_indent}if values_by_id.has("${field.id}"):');
          sb.writeln('${_indent}${_indent}${_indent}instance.$escapedId = $parseExpr');
        }
      }
    }
    return sb.toString();
  }

  String _getAssignValueFunction(DbModel model, GeneratorGdscript data, ClassMetaFieldDescription field) {
    final rawVal = 'values_by_id["${field.id}"]';
    switch (field.typeInfo.type) {
      case ClassFieldType.bool:
        return '_parse_bool($rawVal, context)';
      case ClassFieldType.int:
      case ClassFieldType.long:
      case ClassFieldType.date:
      case ClassFieldType.duration:
        return '_parse_int($rawVal, context)';
      case ClassFieldType.float:
      case ClassFieldType.double:
        return '_parse_float($rawVal, context)';
      case ClassFieldType.string:
      case ClassFieldType.text:
      case ClassFieldType.undefined:
        return '_parse_string($rawVal)';
      case ClassFieldType.color:
        return '_parse_color($rawVal, context)';
      case ClassFieldType.vector2:
        return '_parse_vector2($rawVal, context)';
      case ClassFieldType.vector2Int:
        return '_parse_vector2i($rawVal, context)';
      case ClassFieldType.vector3:
        return '_parse_vector3($rawVal, context)';
      case ClassFieldType.vector3Int:
        return '_parse_vector3i($rawVal, context)';
      case ClassFieldType.vector4:
        return '_parse_vector4($rawVal, context)';
      case ClassFieldType.vector4Int:
        return '_parse_vector4i($rawVal, context)';
      case ClassFieldType.rectangle:
        return '_parse_rect2($rawVal, context)';
      case ClassFieldType.rectangleInt:
        return '_parse_rect2i($rawVal, context)';
      case ClassFieldType.reference:
        final classEntity = model.cache.getEntity(field.typeInfo.classId!);
        if (classEntity is ClassMetaEntityEnum) {
          final enumName = '${data.prefix}${classEntity.id}${data.postfix}';
          final firstVal = classEntity.values.isNotEmpty ? '$enumName.${_escapeIdentifier(classEntity.values.first.id)}' : '0';
          return '$enumName.get(_parse_string($rawVal), $firstVal)';
        }
        return '_parse_reference($rawVal, objects_by_ids, context)';
      case ClassFieldType.list:
      case ClassFieldType.set:
        final innerParser = _getSimpleValueLambda(model, data, field.valueTypeInfo!);
