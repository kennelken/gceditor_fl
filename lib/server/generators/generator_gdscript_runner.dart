  String _getItemsLists(DbModel model, GeneratorGdscript data) {
    final sb = StringBuffer();
    for (final classEntity in model.cache.allClasses) {
      if (classEntity.exportList != true) continue;
      final className = '${data.prefix}${classEntity.id}${data.postfix}';
      final listClassName = '$className${MetaEntityType.Class.name}$_itemsListSuffix';

      final thisAndParentClasses = model.cache.getImplementingClasses(classEntity).concat([classEntity]).map((e) => e.id).toSet();
      final allItems =
          model.cache.allDataTables.where((element) => thisAndParentClasses.contains(element.classId)).toMap((e) => MapEntry(e.classId, e.rows));

      sb.writeln('class $listClassName extends RefCounted:');
      var hasProperties = false;
      for (final kvp in allItems.entries) {
        for (final row in kvp.value) {
          if (row.id.isNotEmpty) {
            final escapedRowId = _escapeIdentifier(row.id);
            sb.writeln('${_indent}var $escapedRowId: $className = null');
            hasProperties = true;
          }
        }
      }
      if (!hasProperties) {
        sb.writeln('${_indent}pass');
      }
      sb.writeln();
      sb.writeln('${_indent}func _init(all_items: Dictionary):');
      var hasInit = false;
      for (final kvp in allItems.entries) {
        for (final row in kvp.value) {
          if (row.id.isNotEmpty) {
            final escapedRowId = _escapeIdentifier(row.id);
            sb.writeln('${_indent}${_indent}if all_items.has("${row.id}"):');
            sb.writeln('${_indent}${_indent}${_indent}$escapedRowId = all_items["${row.id}"]');
            hasInit = true;
          }
        }
      }
      if (!hasInit) {
        sb.writeln('${_indent}${_indent}pass');
      }
      sb.writeln();
    }
    return sb.toString();
  }

